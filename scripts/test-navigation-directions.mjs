import assert from 'node:assert/strict'
import {movementDirection,routeDirectionArrows} from '../src/navigationDirections.js'
let state=movementDirection(null,{lat:52,lng:15,accuracy:10},null,null)
assert.equal(state.heading,null,'No direction is invented before movement')
state=movementDirection(state.anchor,{lat:52.00001,lng:15,accuracy:10},null,null)
assert.equal(state.heading,null,'Stationary GPS jitter does not rotate the triangle')
state=movementDirection(state.anchor,{lat:52.0001,lng:15,accuracy:10},null,null)
assert.ok(Math.abs(state.heading)<.01,'Northbound movement points north')
state=movementDirection(state.anchor,{lat:52.0001,lng:15.0002,accuracy:10},null,null)
assert.ok(Math.abs(state.heading-90)<.01,'Eastbound movement points east')
assert.equal(movementDirection(state.anchor,{lat:52,lng:15},225,2).heading,225,'Use GPS course when provided')
assert.equal(movementDirection(state.anchor,{lat:52.0001,lng:15.0002},0,0).heading,state.heading,'Zero speed never invents a new heading')
const project=([x,y])=>({x,y})
const east=routeDirectionArrows([[0,100],[500,100]],project,{width:500,height:200})
assert.ok(east.length>=5&&east.length<=7)
assert.ok(east.every(p=>p.heading===90&&p.y===100))
const west=routeDirectionArrows([[500,100],[0,100]],project,{width:500,height:200})
assert.ok(west.every(p=>p.heading===270))
const north=routeDirectionArrows([[100,500],[100,0]],project,{width:200,height:500})
assert.ok(north.every(p=>p.heading===0))
const clipped=routeDirectionArrows([[-1e9,100],[1e9,100]],project,{width:390,height:844})
assert.ok(clipped.length>0&&clipped.length<10,'Long segments are clipped before arrow generation')
assert.ok(clipped.every(p=>p.x>=-16&&p.x<=406))
assert.equal(routeDirectionArrows([[0,-100],[100,-100]],project,{width:390,height:844}).length,0)
assert.equal(routeDirectionArrows([[0,100],[5000,100]],project,{width:5000,height:200,max:3}).length,3)
assert.equal(routeDirectionArrows([[0,100],[0,100]],project,{width:390,height:844}).length,0)
console.log('PASS: GPS course, accumulated movement, stationary jitter, route arrow orientation, clipping and density limits')
