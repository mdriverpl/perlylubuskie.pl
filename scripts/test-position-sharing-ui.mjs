import assert from 'node:assert/strict'
import {JSDOM} from 'jsdom'

const dom=new JSDOM('<div id="app"></div>',{url:'https://localhost',pretendToBeVisual:true})
for(const key of ['window','document','Document','ShadowRoot','Element','HTMLElement','SVGElement','Node','Event','KeyboardEvent','localStorage','navigator'])Object.defineProperty(globalThis,key,{value:dom.window[key],configurable:true})
let shared,shareError,refreshes=0
Object.defineProperty(navigator,'share',{configurable:true,value:async value=>{if(shareError)throw shareError;shared=value}})
const {createApp,ref,h,nextTick}=await import('vue')
const Navigation=(await import('../artifacts/trip-navigation-test.mjs')).default
const position=ref(null)
const geometry={type:'LineString',coordinates:[[15.3,52.3],[15.31,52.31]]}
const app=createApp({render:()=>h(Navigation,{position:position.value,geometry,distance:'3',duration:'30 min',onRefresh:()=>refreshes++})})
app.mount('#app')
const settle=async()=>{await nextTick();await new Promise(r=>setTimeout(r,0));await nextTick()}
await settle();document.querySelector('.navigation-share').click();await settle()
assert.equal(refreshes,1,'Opening share without a fix explicitly requests GPS')
assert.equal(document.querySelector('.position-sms'),null,'No fabricated coordinates when GPS is unavailable')
position.value={lat:52.3,lng:15.3,accuracy:8};await settle()
assert.equal(document.querySelector('.position-coordinates').textContent,'52.300000, 15.300000')
assert.equal(new URL(document.querySelector('.position-google').href).searchParams.get('query'),'52.300000,15.300000')
assert.match(decodeURIComponent(document.querySelector('.position-sms').href),/Moja aktualna pozycja GPS: 52.300000, 15.300000/)
assert.match(new URL(document.querySelector('.position-whatsapp').href).searchParams.get('text'),/https:\/\/www.google.com\/maps\/search/)
document.querySelector('.position-share-links button').click();await settle()
assert.match(shared.text,/52.300000, 15.300000/)
assert.match(shared.text,/https:\/\/www.google.com/)
position.value={lat:52.3002,lng:15.3002,accuracy:9};await settle()
assert.match(document.querySelector('.position-coordinates').textContent,/52.300200/)
assert.match(new URL(document.querySelector('.position-whatsapp').href).searchParams.get('text'),/52.300200/,'Messages use the current fix, not the initial position')
document.querySelector('.position-share-links button').click();await settle()
assert.match(shared.text,/52.300200/)
shareError=Object.assign(new Error('cancelled'),{name:'AbortError'})
document.querySelector('.position-share-links button').click();await settle()
assert.equal(document.querySelector('#navigation-share-panel [role=status]'),null,'Cancelling the system share sheet is not an error')
document.querySelector('.position-show-map').click();await settle()
assert.equal(document.querySelector('#navigation-share-panel'),null)
assert.equal(document.querySelector('.test-explore-map').dataset.focusLat,'52.3002')
const saved=JSON.parse(localStorage.getItem('perly:navigation-travelled'))
assert.equal(saved.points.length,2,'Recorded track consists of real, separated GPS fixes')
position.value={lat:52.300201,lng:15.300201,accuracy:8};await settle()
assert.equal(JSON.parse(localStorage.getItem('perly:navigation-travelled')).points.length,2,'Stationary jitter does not add dots')
position.value={lat:52.4,lng:15.4,accuracy:500};await settle()
assert.equal(JSON.parse(localStorage.getItem('perly:navigation-travelled')).points.length,2,'Poor GPS fixes do not pollute the travelled track')
app.unmount();dom.window.close()
console.log('PASS: live coordinates, Google point, SMS/WhatsApp/native share, missing GPS, cancellation, map crosshair focus and persisted travelled dots')
